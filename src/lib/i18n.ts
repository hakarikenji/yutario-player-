const DICTS: Record<LangKey, PartialDict> = { en, ar, es, ja, pt, fr };

let current: LangKey = storageGet<LangKey>("lang", "en");
const listeners = new Set<(l: LangKey) => void>();

export function getLanguage(): LangKey {
  return current;
}

export function setLanguage(lang: LangKey): void {
  if (lang === current) return;
  current = lang;
  storageSet("lang", lang);
  // Apply RTL direction for Arabic at the document level.
  const isRtl = LANGUAGES.find((l) => l.key === lang)?.rtl === true;
  document.documentElement.dir = isRtl ? "rtl" : "ltr";
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn(lang));
}

/** React hook — components re-render the instant the language changes. */
export function useT(): (key: keyof Dict, vars?: Record<string, string | number>) => string {
  const [, force] = useState(0);
  useEffect(() => {
    const fn = () => force((n) => n + 1);
    listeners.add(fn);
    return () => {
      listeners.delete(fn);
    };
  }, []);
  return t;
}

/** t("play_all", { count: 12 }) → "Play All" (interpolation-ready). */
export function t(key: keyof Dict, vars?: Record<string, string | number>): string {
  const dict = DICTS[current] ?? en;
  let s = dict[key] ?? en[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  return s;
}
