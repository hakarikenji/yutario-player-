const DICTS: Record<LangKey, PartialDict> = { en, es, ja, pt, fr };

let current: LangKey = storageGet<LangKey>("lang", "en");

export function getLanguage(): LangKey {
  return current;
}

export function setLanguage(lang: LangKey): void {
  current = lang;
  storageSet("lang", lang);
}

/** t("play_all", { count: 12 }) → "Play All" (interpolation-ready). */
export function t(key: keyof Dict, vars?: Record<string, string | number>): string {
  const dict = DICTS[current] ?? en;
  let s = dict[key] ?? en[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  return s;
}
